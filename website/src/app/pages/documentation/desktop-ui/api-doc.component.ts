import { ChangeDetectionStrategy, Component, computed, forwardRef, input, signal } from '@angular/core';
import { FormsModule } from '@angular/forms';
import { ContentRenderComponent } from '@app/app/components/content-render.component.js';
import { MarkdownParser } from '@app/common/markdown.js';
import { derivedAsync } from 'ngxtension/derived-async';

import {
    InputComponent,
    TableCellDirective,
    TableColumnDirective,
    TableComponent,
    pendingTask,
} from '@deepkit/desktop-ui';
import { CodeHighlightComponent } from '@deepkit/ui-library';

import type { ApiType, ComponentMember } from '../../../../../api-docs';

// generated by api-docs.ts
const docs = import('../../../../../api-docs.json').then(
    v => ((v as any).default || v)['@deepkit/desktop-ui'] as ApiType[],
);
const markdownParser = new MarkdownParser();

const kindOrder: { [kind: string]: number } = {
    'input required': 1,
    input: 2,
    output: 3,
    property: 4,
    method: 5,
};

function sortKey(member: ComponentMember): number {
    return kindOrder[member.kind + (member.required ? ' required' : '')];
}

@Component({
    selector: 'api-doc',
    template: `
        <div>
            <div class="title">
                <h2>
                    API
                    <code>{{ title() }}</code>
                    @if (apiDoc(); as doc) {
                        <small
                            >(<a
                                href="https://github.com/deepkit/deepkit-framework/tree/master/{{ doc.source.file }}#L{{
                                    doc.source.line
                                }}"
                                target="_blank"
                                rel="noopener noreferrer"
                                >source</a
                            >)</small
                        >
                    }
                </h2>
                @if (members().length) {
                    <dui-input icon="search" placeholder="Search" [(ngModel)]="filterQuery" clearer></dui-input>
                }
            </div>
            @if (apiDoc()?.component?.formsCompatible) {
                <div class="forms-compatible">
                    This component is compatible with Angular Forms. You can use <code>[(ngModel)]</code> or
                    <code>formControlName</code> with it.
                </div>
            }
            @if (comment(); as content) {
                <app-render-content [content]="content.body"></app-render-content>
            }
            @if (members().length) {
                <dui-table
                    [virtualScrolling]="false"
                    [items]="members()"
                    [filterQuery]="filterQuery()"
                    [filterFields]="['name', 'kind', 'type', 'description']"
                    no-focus-outline
                    text-selection
                >
                    <dui-table-column name="name" header="Name" [width]="450">
                        <ng-container *duiTableCell="let row">
                            <code-highlight lang="typescript" inline [code]="code(row)" />
                        </ng-container>
                    </dui-table-column>
                    <dui-table-column name="description" header="Description" [width]="350"></dui-table-column>
                </dui-table>
            }
        </div>
    `,
    styleUrls: ['./api-doc.component.scss'],
    changeDetection: ChangeDetectionStrategy.Eager,
    imports: [
        TableComponent,
        TableColumnDirective,
        InputComponent,
        FormsModule,
        TableCellDirective,
        forwardRef(() => ContentRenderComponent),
        CodeHighlightComponent,
    ],
})
export class ApiDocComponent {
    component = input.required<string>();

    filterQuery = signal('');

    apiDoc = derivedAsync(
        pendingTask(async () => {
            const name = this.component();
            const doc = (await docs).find(v => v.name === name && v.kind === 'class');
            if (!doc) throw new Error(`No API docs for ${name} in @deepkit/desktop-ui found.`);
            return doc;
        }),
    );

    title = computed(() => {
        const doc = this.apiDoc();
        if (!doc) return '';
        const selector = doc.component?.selector;
        if (!selector) return doc.name;
        return selector.startsWith('[') ? selector : '<' + selector.replace(/,\s*/g, '>, <') + '>';
    });

    members = computed(() =>
        [...(this.apiDoc()?.component?.members || [])].sort(
            (a, b) => sortKey(a) - sortKey(b) || a.name.localeCompare(b.name),
        ),
    );

    comment = derivedAsync(
        pendingTask(async () => {
            const description = this.apiDoc()?.description;
            if (!description) return undefined;
            return markdownParser.loadAndParse(description);
        }),
    );

    code(row: ComponentMember) {
        let prefix = row.alias || row.name;
        if (row.kind === 'input') {
            prefix = '@Input() ' + prefix;
            if (!row.required) prefix += '?';
        } else if (row.kind === 'output') {
            prefix = '@Output() ' + prefix + '?';
        }

        return prefix + ': ' + row.type;
    }
}
